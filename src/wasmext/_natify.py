"""`natify()`: the `.wasm` files of a project become setuptools `Extension`s, as `cythonize()` does for `.pyx` files.

    # setup.py
    from setuptools import setup
    from wasmext import natify

    setup(ext_modules=natify(["src/mypkg/*.wasm"]))

The C of each module (the glue, the output of `wasm2c`, the runtime of the same version) is written to a directory
beside the `.wasm` (`<name>_wasmext/`, or under `build_dir`) when `natify()` runs, and is not written again while the
`.wasm` is older than the C and it was made by this wasmext (the first line says so, as in the C of Cython). A project that ships those directories in its sdist builds without `wasm2c`, with a C compiler only.
"""

