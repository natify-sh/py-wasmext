class _Reference:
    """The reference to an export of an instance of this wrapper, for another instance to import. It holds the record that the library filled and the instance, so they live as long as
    it does; an extension reads it through `__wasmext_ref__`, which is a capsule over the record (valid while this object is). It is an object and not a capsule because a capsule
    has to have a destructor to keep the instance alive, and a destructor of ctypes cannot run while an exception is being raised (a failed link frees the references it was given:
    ctypes refuses to be called then, and the call fails with that exception's message)."""

    __slots__ = ("_record", "_owner", "__weakref__")

    def __init__(self, record: Any, owner: Any) -> None:
        self._record = record
        self._owner = owner

    @property
    def __wasmext_ref__(self) -> Any:
        return _capi.PyCapsule_New(_c.addressof(self._record), _CAPSULE, None)


def _capsule_of(reference: Any) -> Any:
    """The capsule that a reference to an export stands for: itself (the capsule of an extension), or what its `__wasmext_ref__` gives (the references of this wrapper, which each
    wrapper has a class of its own for, and the objects that hold one), or None."""
    for _ in range(3):
        if _capi.PyCapsule_IsValid(reference, _CAPSULE):
            return reference
        reference = getattr(reference, "__wasmext_ref__", None)
        if reference is None:
            return None
    return None


def _is_capsule(reference: Any) -> bool:
    return _capsule_of(reference) is not None


def _record_of(reference: Any) -> Any:
    """The record behind a reference to an export (of an extension or of a wrapper like this one), or None. It lives as long as the reference does."""
    capsule = _capsule_of(reference)
    if capsule is None:
        return None
    record = _c.cast(_capi.PyCapsule_GetPointer(capsule, _CAPSULE), _c.POINTER(_Export)).contents
    record._capsule = capsule  # type: ignore[attr-defined]  # a Table of an extension gives a new capsule each time, and the record lives only as long as its capsule does
    return record


def _function_of(record: Any) -> Any:
    """The callable that stands for a function export of an instance of an extension (its record says whose it is): the same function, called through Python."""
    owner = _c.cast(record.owner, _c.py_object).value
    for name, reference in owner.__exports__.items():
        other = _record_of(reference)
        if other is not None and other.kind == _FUNC and other.address == record.address and other.instance == record.instance:
            return getattr(owner, name)
    raise LinkError("the function export given is of an instance that does not show it as a method")


