def _find_import(imports: Any, module: str, field: str, *, required: bool = True, check: bool = True) -> Any:
    try:
        shelf = imports[module]
    except (KeyError, TypeError, IndexError):
        if not required:
            return None
        raise LinkError(f"missing import module '{module}'") from None
    exports = getattr(shelf, "__exports__", None)  # a shelf that is an instance of a wasmext module gives its exports
    if exports is not None:
        shelf = exports
    try:
        function = shelf[field]
    except (KeyError, TypeError, IndexError):
        if not required:
            return None
        raise LinkError(f"missing import '{module}.{field}'") from None
    return function


def _method(name: str, cname: str, params: tuple[str, ...], results: tuple[str, ...]) -> Callable[..., Any]:
    count = len(params)

    def method(self: Instance, *args: Any) -> Any:
        if len(args) != count:
            raise TypeError(f"{name}() takes exactly {count} argument{'' if count == 1 else 's'} ({len(args)} given)")
        return self._call(cname, params, results, args)

    method.__name__ = method.__qualname__ = name
    method.__doc__ = _signature(name, params, results)
