"""A native executable from a WebAssembly command: the first host of the C layers that is not Python (item 10 of DESIGN.md, stage 5).

`build(module.wasm, program)` makes the C of the module with wasm2c (the way `natify` does), writes a `main()` that uses the glue of the module
(`<name>_glue.h`) and the core of WASI (`wasi_p1_core.h`) with no Python in it, and compiles and links all of it. The program runs the `_start` of the
module: `--env NAME=VALUE` and `--dir HOST::GUEST` (both may be repeated) give it an environment and the directories it may reach, then comes the path of the
module (its name for the program, `argv[0]`), then the arguments. It ends with the code of `proc_exit`, or 134 on a trap (what the Python runner of the
test suite answers too). Only the imports of WASI are served: another import is refused when the program is made.
"""

from __future__ import annotations

import importlib
import os
import re
import shutil
import sys
from collections.abc import Sequence
from dataclasses import dataclass, replace
from pathlib import Path
from typing import Any

from ._natify import generate_c, signal_build_flags

_MAIN = r"""/* Generated by wasmext from the WebAssembly module of @LAST@: do not edit. The executable: main(), the glue of the module and the core of WASI; no Python. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#ifdef _WIN32
#include <fcntl.h>
#include <io.h>
#endif
#include "@LAST@_glue.h"

@HELPERS@
@NET@static @LAST@_instance instance;
static @LAST@_store store;  /* the store of the program: the executable makes it by hand, as every host does */

#ifdef _WIN32
#include <windows.h>
#include <shellapi.h>
/* the arguments as UTF-8: the narrow ones of the C runtime are in the code page of the console, and lose what it cannot hold */
static char **run_utf8_argv(int *count) {
    int n = 0;
    wchar_t **wide = CommandLineToArgvW(GetCommandLineW(), &n);
    if (wide == NULL) return NULL;
    char **out = (char **)calloc((size_t)n + 1, sizeof(char *));
    for (int i = 0; out != NULL && i < n; i++) {
        int size = WideCharToMultiByte(CP_UTF8, 0, wide[i], -1, NULL, 0, NULL, NULL);
        out[i] = (char *)malloc((size_t)size + 1);
        if (out[i] == NULL || WideCharToMultiByte(CP_UTF8, 0, wide[i], -1, out[i], size, NULL, NULL) == 0) return NULL;
    }
    *count = n;
    return out;
}
#endif

static void run_usage(FILE *to, const char *self) {
    fprintf(to,
            "usage: %s [options] [--] [program-name [arguments]]\n"
            "  --env NAME=VALUE      an environment variable of the program (repeatable)\n"
            "  --dir HOST[::GUEST][:ro]\n"
            "                        a directory the program may reach, as GUEST (\"/\" by default); :ro: read only (repeatable)\n"
            "  --argv0 NAME          the name the program has for itself (else the first argument that is not an option)\n"
@NETUSAGE@            "  --version             print the name of the module and of wasmext\n"
            "  -h, --help            this text\n"
            "the program ends with the code of proc_exit, 134 on a trap, 2 when the options are wrong\n",
            self);
}

int main(int argc, char **argv) {
    instance.store = &store;
#ifdef _WIN32
    _setmode(0, _O_BINARY);  /* the bytes of the program, not text: no "\n" turned into "\r\n" */
    _setmode(1, _O_BINARY);
    _setmode(2, _O_BINARY);
    {
        char **utf8 = run_utf8_argv(&argc);
        if (utf8 != NULL) argv = utf8;
    }
#endif
    char **env = (char **)calloc((size_t)argc + 1, sizeof(char *));
    char **dirs = (char **)calloc((size_t)argc + 1, sizeof(char *));
    const char *argv0 = NULL;
    int nenv = 0, ndirs = 0, i = 1;
    for (; i < argc; i++) {  /* the options come first, then the program, then its arguments */
        const char *a = argv[i];
        int more = i + 1 < argc;
        if (strcmp(a, "--") == 0) {
            i++;
            break;
        } else if (strcmp(a, "-h") == 0 || strcmp(a, "--help") == 0) {
            run_usage(stdout, argv[0]);
            return 0;
        } else if (strcmp(a, "--version") == 0) {
            printf("@LAST@ (wasmext @VERSION@)\n");
            return 0;
@NETOPT@        } else if (strcmp(a, "--env") == 0 || strcmp(a, "--dir") == 0 || strcmp(a, "--argv0") == 0) {
            if (!more) {
                fprintf(stderr, "%s: %s needs a value\n", argv[0], a);
                return 2;
            }
            char *value = argv[++i];
            if (strcmp(a, "--env") == 0) {
                const char *eq = strchr(value, '=');
                if (eq == NULL || eq == value) {
                    fprintf(stderr, "%s: --env wants NAME=VALUE, not \"%s\"\n", argv[0], value);
                    return 2;
                }
                env[nenv++] = value;
            } else if (strcmp(a, "--dir") == 0) {
                dirs[ndirs++] = value;
            } else {
                argv0 = value;
            }
        } else if (a[0] == '-' && a[1] == '-') {
            fprintf(stderr, "%s: unknown option %s (-h for the list)\n", argv[0], a);
            return 2;
        } else {
            break;
        }
    }
    char *program = i < argc ? argv[i] : argv[0];  /* argv[0] of the program is the path it is given as */
    if (argv0 != NULL) {  /* named by --argv0: everything that follows is for the program */
        program = (char *)argv0;
        i--;
    }
    char **args = (char **)calloc((size_t)(argc - i) + 2, sizeof(char *));
    int nargs = 0;
    args[nargs++] = program;
    for (int k = i + 1; k < argc; k++) args[nargs++] = argv[k];

@RUN@"""

# the part of the program that both snapshots share: the state of the host (0.2's) filled from the command line
_RUN_STATE = """    fusedwasi_p2_state *s;
    int allow_net = 0;
    wasm_rt_init();
    @LAST@_wasi_bind(&instance);  /* the state of the host is made (fusedwasi_p2_init), and the guest of the instance and its imports are bound to it, for 0.1 as for 0.2 */
    s = &instance.store->wasi;
    allow_net = run_allow_net;
    if (allow_net) {  /* nothing of the network is allowed unless the options say so, as in Wasmtime */
        s->socket_addr_check = run_net_yes;
        s->http_check = run_http_yes;
        s->allow_ip_name_lookup = 1;
    }
    s->args = (const char *const *)args;
    s->arg_count = (uint32_t)nargs;
    {
        const char **names = (const char **)calloc((size_t)nenv + 1, sizeof(char *));
        const char **values = (const char **)calloc((size_t)nenv + 1, sizeof(char *));
        for (int k = 0; k < nenv; k++) {
            char *eq = strchr(env[k], '=');  /* checked above: there is one */
            *eq = '\\0';
            names[k] = env[k];
            values[k] = eq + 1;
        }
        s->env_names = names;
        s->env_values = values;
        s->env_count = (uint32_t)nenv;
    }
    struct fusedwasi_p2_preopen *preopens = (struct fusedwasi_p2_preopen *)calloc((size_t)ndirs + 1, sizeof *preopens);
    for (int k = 0; k < ndirs; k++) {
        char *separator = strstr(dirs[k], "::");
        size_t length = strlen(dirs[k]);
        preopens[k].writable = 1;
        if (length >= 3 && strcmp(dirs[k] + length - 3, ":ro") == 0 && (separator != NULL || length > 3)) {
            dirs[k][length - 3] = '\\0';
            preopens[k].writable = 0;
        }
        if (separator != NULL) *separator = '\\0';
        preopens[k].path = dirs[k];
#ifdef _WIN32
        {  /* the whole path, as Windows wants it for a name below it */
            char full[4096];
            if (_fullpath(full, dirs[k], sizeof full) != NULL) preopens[k].path = _strdup(full);
        }
#endif
        preopens[k].name = separator != NULL && separator[2] != '\\0' ? separator + 2 : "/";
    }
    s->preopens = preopens;
    s->preopen_count = (uint32_t)ndirs;
"""

_RUN_P1 = """    (void)program;
    {
        int error = 0;
        size_t bad = (size_t)-1;
        if (fusedwasi_p1_open_descriptors(s, &error, &bad) != 0) {  /* a directory that cannot be opened is told now, with its place in the list */
            if (bad != (size_t)-1) fprintf(stderr, "%s: --dir %s: %s\\n", argv[0], dirs[bad], strerror(error));
            else fprintf(stderr, "%s: cannot set up WASI: %s\\n", argv[0], strerror(error));
            return 2;
        }
    }
    int trapped = @LAST@_glue_instantiate(&instance);
    if (!trapped) {
        @LAST_U@_START(&instance.inst, &trapped);
    }
    int code = 0;
    if (instance.guest.exited) {  /* proc_exit: its code, as wasi:cli/exit gives it */
        code = (int)instance.guest.exit_code;
    } else if (instance.signalled) {
        fprintf(stderr, "%s: the program was ended by the signal %u\\n", argv[0], (unsigned)instance.signalled);
        code = 134;
    } else if (trapped) {
        if (instance.store->p2_message[0] != '\\0') fprintf(stderr, "trap: %s\\n", instance.store->p2_message);
        else fprintf(stderr, "trap: %s\\n", wasm_rt_strerror((wasm_rt_trap_t)trapped));
        code = 134;
    }
    fflush(stdout);
    @LAST@_glue_free(&instance);
    fusedwasi_p2_free(s);
    return code;
}
"""

_RUN_P2 = """    int trapped = @LAST@_glue_instantiate(&instance);
    if (!trapped) trapped = @LAST@_glue_initialize(&instance);
    uint32_t result = 0;
    if (!trapped) {
        result = (uint32_t)@LAST_U@_RUN(&instance.inst, &trapped);
    }
    int code = 0;
    if (instance.guest.exited) {  /* wasi:cli/exit: its code; the call came back as a trap of the host */
        code = (int)instance.guest.exit_code;
    } else if (trapped) {
        if (instance.store->p2_message[0] != '\\0') fprintf(stderr, "trap: %s\\n", instance.store->p2_message);
        else fprintf(stderr, "trap: %s\\n", wasm_rt_strerror((wasm_rt_trap_t)trapped));
        code = 134;
    } else {
        code = result != 0 ? 1 : 0;  /* the result of run: 0 is ok, 1 is err */
    }
    fflush(stdout);
    @LAST@_glue_free(&instance);
    fusedwasi_p2_free(s);
    return code;
}
"""

_MAIN_P1 = {
    "@HELPERS@": '#if !@LAST_U@_WASI || !@LAST_U@_ONLY_WASI\n#error "wasmext: an executable serves the imports of WASI and no others"\n#endif\n#ifndef @LAST_U@_START\n#error "wasmext: the module has no _start () -> ()"\n#endif\n',
    "@NET@": "static int run_allow_net;  /* nothing of the network is allowed: no option for it */\nstatic int run_net_yes(fusedwasi_p2_state *s, const char *ip, uint16_t port, int use) {\n    (void)s; (void)ip; (void)port; (void)use;\n    return 1;\n}\nstatic int run_http_yes(fusedwasi_p2_state *s, const char *scheme, const char *authority) {\n    (void)s; (void)scheme; (void)authority;\n    return 1;\n}\n",
    "@NETOPT@": "",
    "@NETUSAGE@": "",
}

_MAIN_P2 = {
    "@HELPERS@": '#if !@LAST_U@_WASI || !@LAST_U@_ONLY_WASI\n#error "wasmext: an executable serves the imports of WASI and no others"\n#endif\n#ifndef @LAST_U@_RUN\n#error "wasmext: the module does not export wasi:cli/run@0.2.x#run () -> i32"\n#endif\n',
    "@NET@": "static int run_allow_net;  /* --allow-net */\nstatic int run_net_yes(fusedwasi_p2_state *s, const char *ip, uint16_t port, int use) {\n    (void)s; (void)ip; (void)port; (void)use;\n    return 1;\n}\nstatic int run_http_yes(fusedwasi_p2_state *s, const char *scheme, const char *authority) {\n    (void)s; (void)scheme; (void)authority;\n    return 1;\n}\n",
    "@NETOPT@": '        } else if (strcmp(a, "--allow-net") == 0) {\n            run_allow_net = 1;\n',
    "@NETUSAGE@": '            "  --allow-net           the program may use the network (sockets, name lookup, http); else all of it is refused\\n"\n',
}


def main_c(last: str, prefix: str, host: str = "wasm32-wasip1") -> str:
    """The C of the `main()` of a program for the module `last` (`prefix`: the name wasm2c makes of it) over the host `wasm32-wasip1` or `wasm32-wasip2`."""
    from . import __version__

    text = _MAIN
    parts = _MAIN_P2 if host == "wasm32-wasip2" else _MAIN_P1
    for key, value in parts.items():
        text = text.replace(key, value)
    text = text.replace(
        "@RUN@", _RUN_STATE + (_RUN_P2 if host == "wasm32-wasip2" else "    (void)program;\n" + _RUN_P1)
    )
    return (
        text.replace("@LAST_U@", last.upper())
        .replace("@LAST@", last)
        .replace("@PREFIX@", prefix)
        .replace("@VERSION@", __version__)
    )


@dataclass(frozen=True)
class BuildFlags:
    """What the user adds to the build of a library or a program, by the names that `setuptools.Extension` has (and `[tool.wasmext.ext-modules]` of pyproject.toml). They come after
    the flags of wasmext, so that they win (`-O3` after `-O1`); the environment is read as setuptools reads it (CC, CFLAGS, CPPFLAGS and LDFLAGS; `_CL_` for MSVC)."""

    extra_compile_args: Sequence[str] = ()
    extra_link_args: Sequence[str] = ()
    define_macros: Sequence[tuple[str, str | None]] = ()
    undef_macros: Sequence[str] = ()
    include_dirs: Sequence[str] = ()
    libraries: Sequence[str] = ()
    library_dirs: Sequence[str] = ()


def _exported_names(api_header: str) -> list[str]:
    """The functions of the C API (WASMEXT_API in the header): the only symbols that a library shows."""
    return re.findall(r"^WASMEXT_API\s+[^;(]*?\b([A-Za-z_]\w*)\s*\(", api_header, re.MULTILINE)


def _export_args(names: list[str], out_dir: Path, last: str) -> list[str]:
    """The arguments of the linker that make the library show those names and no others, whatever the flags of the compiler were. Two libraries then have a copy of the runtime of
    wasm2c each (as two extensions have), and the references to it bind inside the library: a global of the runtime is not shared between them. (MSVC: only what is `dllexport`.)"""
    if sys.platform == "win32":
        return []
    if sys.platform == "darwin":
        listing = out_dir / f"{last}.exports"
        listing.write_text("".join(f"_{n}\n" for n in names), encoding="utf-8")
        return [f"-Wl,-exported_symbols_list,{listing.as_posix()}"]
    script = out_dir / f"{last}.map"
    script.write_text(
        "{\n  global:\n" + "".join(f"    {n};\n" for n in names) + "  local:\n    *;\n};\n", encoding="utf-8"
    )
    return [f"-Wl,--version-script={script.as_posix()}"]


def _system_libraries(msvc: bool, *, program: bool = False) -> list[str]:
    """What the C of wasmext needs from the system: the maths library; on Windows `bcrypt` (the random bytes; MSVC finds it by a pragma, MinGW has to be told) and,
    for a program, `shell32` (its arguments as UTF-8)."""
    if sys.platform == "win32":
        return ["bcrypt", *(["shell32"] if program else [])]
    return [] if msvc else ["m"]


def _compiler() -> Any:
    from distutils import sysconfig  # pyright: ignore[reportMissingModuleSource]
    from distutils.ccompiler import new_compiler  # pyright: ignore[reportMissingModuleSource]

    importlib.import_module(
        "setuptools"
    )  # puts the distutils of setuptools in place of the one of the standard library

    compiler = new_compiler()
    sysconfig.customize_compiler(compiler)
    return compiler


def _compile_sources(
    sources: list[str], prepared: object, out_dir: Path, *, optimize: bool, flags: BuildFlags
) -> tuple[Any, list[str], bool]:
    """Compile `sources` with the compiler of setuptools; returns the compiler, the objects and whether it is MSVC."""
    compiler = _compiler()
    msvc = compiler.compiler_type == "msvc"

    def flat(names: list[str], strip_dir: bool = False, output_dir: str = "") -> list[str]:
        # distutils lays an object out under the whole path of its source, which is past the 260 characters of Windows in a deep directory
        return [os.path.join(output_dir, Path(n).stem + compiler.obj_extension) for n in names]

    compiler.object_filenames = flat  # the stems of the sources of one module are all different
    # no warnings: the C of wasm2c and its runtime are not ours to police
    ours: list[str] = ["/w"] if msvc else ["-w"]
    if not optimize:
        ours += ["/Od"] if msvc else ["-O0"]
    elif not msvc:
        ours += ["-O1"]
    objects = compiler.compile(
        sources,
        output_dir=str(out_dir / "obj"),
        macros=[*flags.define_macros, *[(name,) for name in flags.undef_macros]],
        include_dirs=[prepared.include_dir, *prepared.extra_include_dirs, *flags.include_dirs],  # type: ignore[attr-defined]
        extra_postargs=[*ours, *flags.extra_compile_args],  # the flags of the user come after ours, and win
    )
    return compiler, objects, msvc


def program_problem(parsed: Any, host: str = "wasm32-wasip1") -> str:
    """Why the module cannot be a program (a command), or an empty string: it serves the imports of WASI and no others, and has a `_start () -> ()` (host `wasm32-wasip1`) or
    exports `wasi:cli/run@0.2.x#run () -> i32` (host `wasm32-wasip2`). The program answers the imports of WASI itself, so the host must be one of those two."""
    if host not in ("wasm32-wasip1", "wasm32-wasip2"):
        return f"an executable is a WASI program and the host is {host!r}: say host 'wasm32-wasip1' or 'wasm32-wasip2'"
    if host == "wasm32-wasip2":
        other = next((i for i in parsed.imports if not re.fullmatch(r"wasi:[\w-]+/[\w-]+@0\.2\.\d+", i.module)), None)
        if other is not None:
            return f"an executable serves the imports of WASI 0.2 and no others (import {other.module}.{other.name})"
        if not any(i.module.startswith("wasi:") for i in parsed.imports):
            return "an executable is a WASI program, and the module imports nothing from WASI"
        run = next((t for n, t in parsed.func_exports() if re.fullmatch(r"wasi:cli/run@0\.2\.\d+#run", n)), None)
        if run is None:
            return "an executable runs wasi:cli/run@0.2.x#run of a command, and the module does not export it"
        if run.params or [str(r) for r in run.results] != ["i32"]:
            return f"run is ({', '.join(run.params)}) -> ({', '.join(run.results)}), a command has run () -> (i32)"
        return ""
    other = next((i for i in parsed.imports if i.module not in ("wasi_snapshot_preview1", "wasi_unstable")), None)
    if other is not None:
        return f"an executable serves the imports of WASI and no others (import {other.module}.{other.name})"
    if not any(i.module in ("wasi_snapshot_preview1", "wasi_unstable") for i in parsed.imports):
        return "an executable is a WASI program, and the module imports nothing from WASI"
    start = next((t for n, t in parsed.func_exports() if n == "_start"), None)
    if start is None:
        return "an executable runs the _start of a command, and the module has none"
    if start.params or start.results:
        return f"_start is ({', '.join(start.params)}) -> ({', '.join(start.results)}), a command has _start () -> ()"
    return ""


def _name_of(wasm_path: Path, name: str | None) -> str:
    last = name or "".join(c if c.isalnum() else "_" for c in wasm_path.stem)
    return f"m_{last}" if not last or last[0].isdigit() else last


def build_shared(
    wasm: str | os.PathLike[str],
    library: str | os.PathLike[str],
    *,
    name: str | None = None,
    work: str | os.PathLike[str] | None = None,
    parts: int | None = None,
    share_tables: bool = False,
    host: str = "wasm32",
    optimize: bool = True,
    quiet: bool = False,
    wrapper: bool = True,
    flags: BuildFlags | None = None,
) -> Path:
    """Make the shared library `library` of the module `wasm`; beside the C, in `work`, is its header `<name>_api.h`: the C API for a host that is not
    Python (see _shared.py). With `wrapper`, beside the library are `<name>_ctypes.py` and its `.pyi`: the interface of the extension over ctypes
    (see _ctypes_gen.py). `flags` adds to the build (see BuildFlags). The library shows the functions of its API and no other symbol, by the linker.
    The C of every target is made by `generate_c` (see _natify.py), which is separate: a project may make the C first (as `cythonize` does) and build later."""
    from ._gen import GenError

    wasm_path, library_path = Path(wasm), Path(library)
    if work is None:
        work = library_path.parent / f"{library_path.stem}_wasmext"
    last = _name_of(wasm_path, name)
    out_dir = Path(work)
    generated = generate_c(
        wasm_path,
        last,
        out_dir,
        force=False,
        quiet=True,
        stubs=False,
        parts=parts,
        share_tables=share_tables,
        host=host,
    )
    chosen = generated.targets["shared"]
    if chosen.reason:
        raise GenError(f"{wasm_path}: {chosen.reason}")
    prepared, glue = generated.prepared, generated.prepared.glue
    if not quiet:
        for item in generated.skipped:
            print(f"wasmext: {wasm_path}: not in the library: {item}", file=sys.stderr)
    flags = flags or BuildFlags()
    if glue.trap_handler:  # the module shares tables with other libraries: its traps go to the innermost call into WebAssembly code (wasmext_glue.h)
        flags = replace(flags, define_macros=[*flags.define_macros, ("WASMEXT_TRAP_HANDLER", glue.trap_handler)])
    chain_macros, chain_link = (
        signal_build_flags()
    )  # as for an extension: the library installs a link of a chain of handlers of signals
    if chain_macros:
        flags = replace(
            flags,
            define_macros=[*flags.define_macros, *chain_macros],
            extra_link_args=[*flags.extra_link_args, *chain_link],
        )
    compiler, objects, msvc = _compile_sources(chosen.sources, prepared, out_dir, optimize=optimize, flags=flags)
    library_path.parent.mkdir(parents=True, exist_ok=True)
    if (
        sys.platform == "darwin"
    ):  # Python links a bundle (a plug-in, which nothing can link against), and a library is a dylib
        linker: list[str] = compiler.linker_so
        compiler.linker_so = [
            "-dynamiclib" if a == "-bundle" else a for a in linker if a not in ("-undefined", "dynamic_lookup")
        ]
    compiler.link_shared_object(
        objects,
        str(library_path),
        libraries=[*_system_libraries(msvc), *flags.libraries],
        library_dirs=list(flags.library_dirs),
        extra_postargs=[*_export_args(_exported_names(glue.api_header), out_dir, last), *flags.extra_link_args],
    )
    if (
        glue.api_model is not None and wrapper
    ):  # the front end for ctypes, beside the library, with the types of the extension
        from ._ctypes_gen import generate_ctypes

        (library_path.parent / f"{last}_ctypes.py").write_text(
            generate_ctypes(glue.api_model, library_file=library_path.name), encoding="utf-8"
        )
        (library_path.parent / f"{last}_ctypes.pyi").write_text(glue.stub, encoding="utf-8")
    if msvc:  # the import library (what a host links against) is written beside the objects; put it beside the dll
        implib = Path(objects[0]).parent / f"{library_path.stem}.lib"
        if implib.is_file():
            shutil.copyfile(implib, library_path.with_suffix(".lib"))
    return library_path


def build(
    wasm: str | os.PathLike[str],
    program: str | os.PathLike[str],
    *,
    name: str | None = None,
    work: str | os.PathLike[str] | None = None,
    parts: int | None = None,
    share_tables: bool = False,
    host: str = "wasm32",
    optimize: bool = True,
    flags: BuildFlags | None = None,
) -> Path:
    """Make `program` (an executable) from the command `wasm`; the C is made in `work` (beside the program by default). `flags` adds to the build (see BuildFlags). Returns its path.
    The C is made by `generate_c`, which is separate."""
    from ._gen import GenError

    wasm_path, program_path = Path(wasm), Path(program)
    if work is None:
        work = program_path.parent / f"{program_path.stem}_wasmext"
    out_dir = Path(work)
    generated = generate_c(
        wasm_path,
        _name_of(wasm_path, name),
        out_dir,
        force=False,
        quiet=True,
        stubs=False,
        parts=parts,
        share_tables=share_tables,
        host=host,
    )
    chosen = generated.targets["exe"]
    if chosen.reason:
        raise GenError(f"{wasm_path}: {chosen.reason}")
    prepared = generated.prepared
    flags = flags or BuildFlags()
    compiler, objects, msvc = _compile_sources(chosen.sources, prepared, out_dir, optimize=optimize, flags=flags)
    program_path.parent.mkdir(parents=True, exist_ok=True)
    # `link_executable` adds the extension of programs itself (`.exe` of MSVC): a name that has it already would be `m.exe.exe`
    suffix = compiler.exe_extension or ""
    named = str(program_path)
    if suffix and named.lower().endswith(suffix):
        named = named[: -len(suffix)]
    libraries = (
        ["shell32", *(["ws2_32", "bcrypt"] if host == "wasm32-wasip2" else [])]
        if msvc or sys.platform == "win32"
        else ["m"]
    )  # shell32: the arguments of the program as UTF-8; the sockets and the random bytes of WASI 0.2
    compiler.link_executable(
        objects,
        named,
        libraries=[*libraries, *flags.libraries],
        library_dirs=list(flags.library_dirs),
        extra_postargs=list(flags.extra_link_args),
    )
    made = Path(compiler.executable_filename(named))
    if made != program_path and made.is_file():
        made.replace(program_path)
    return program_path


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print("usage: python -m wasmext._exe module.wasm program", file=sys.stderr)
        return 2
    build(argv[0], argv[1])
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
