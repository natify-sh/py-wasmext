def generate_ctypes(model: ApiModel, *, library_file: str, version: str | None = None) -> str:
    """The text of `<name>_ctypes.py` for the module of `model`; `library_file` is the name of the shared library beside it."""
    name = model.last
    uses_wasi = model.uses_wasi
    exports = [(n, c, tuple(f.params), tuple(f.results)) for n, c, f in model.exports]
    imports = [
        (k, module, field, tuple(f.params), tuple(f.results), wasi_call)
        for k, module, field, f, wasi_call in model.imports
    ]
    text = _TEMPLATE
    uncaught_class = _UNCAUGHT_CLASS if model.has_tags else ""
    wasi_exceptions = _WASI_EXCEPTIONS if uses_wasi else ""
    parts = {
        "@UNCAUGHT@": uncaught_class,
        "@WASI_EXCEPTIONS@": wasi_exceptions,
        "@EXCEPTION_SETUP@": _UNCAUGHT_SETUP if model.has_tags else "",
        "@UNCAUGHT_ERROR@": _UNCAUGHT_ERROR if model.has_tags else "",
        "@WASI_RUNTIME@": _WASI_RUNTIME if uses_wasi else "",
        "@WASI_METHODS@": (_WASI_METHODS if uses_wasi else "") + (_UNCAUGHT_METHOD if model.has_tags else ""),
        "@WASI_CONFIG_CALL@": "_wasi_config(weakref.ref(self), wasi)" if uses_wasi else "(None, [])",
        "@EXPORTS@": _py(exports),
        "@MEMORIES@": _py(list(model.memories)),
        "@GLOBALS@": _py(list(model.globals)),
        "@IMPORTS@": _py(imports),
        "@GLOBAL_IMPORTS@": _py([tuple(g) for g in model.global_imports]),
        "@MEMORY_IMPORTS@": _py([tuple(m) for m in model.memory_imports]),
        "@USES_WASI@": _py(uses_wasi),
        "@HAS_TAGS@": _py(model.has_tags),
        "@VERSION@": f" {version}" if version else "",
        "@LIBRARY@": library_file,
        "@LIBRARY_FILE@": _py(library_file),
        "@ENV@": f"WASMEXT_{name.upper()}_LIBRARY",
        "@NAME@": name,
    }
    for key, value in parts.items():
        text = text.replace(key, value)
    return text
