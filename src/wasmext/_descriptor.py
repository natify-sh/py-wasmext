"""The C of the descriptor of a module (`<name>_descriptor.c`): read-only data made from the model, see `c/wasmext_descriptor.h`."""

from __future__ import annotations

from ._model import KIND_CODES, VALTYPE_BYTES, ExportFact, ImportFact, ModuleModel, Type
from ._wasm import FuncType, Limits

__all__ = ["generate_descriptor"]


def _bytes_lit(text: str) -> str:
    """A C string literal of the UTF-8 bytes, in octal escapes where a byte is not plain (an octal escape has three digits, so what follows cannot join it)."""
    out: list[str] = []
    for b in text.encode("utf-8", "surrogatepass"):
        c = chr(b)
        if 0x20 <= b < 0x7F and c not in '"\\?':
            out.append(c)
        else:
            out.append(f"\\{b:03o}")
    return '"' + "".join(out) + '"'


def _str(text: str | None) -> str:
    if text is None:
        return "{0, 0}"
    return f"{{{_bytes_lit(text)}, {len(text.encode('utf-8', 'surrogatepass'))}u}}"


def _limits(lim: Limits) -> str:
    maximum = 0 if lim.max is None else lim.max
    return f"{{{lim.min}ull, {maximum}ull, {int(lim.max is not None)}, {int(lim.shared)}, {int(lim.is64)}}}"


class _Emitter:
    def __init__(self, prefix: str) -> None:
        self.prefix = prefix
        self.lines: list[str] = []
        self.count = 0

    def types(self, ft: FuncType) -> str:
        """The initializer of a `wasmext_functype`, with its arrays emitted before."""
        if not ft.params and not ft.results:
            return "{0, 0, 0, 0}"
        n = self.count = self.count + 1
        parts: list[str] = []
        for tag, seq in (("p", ft.params), ("r", ft.results)):
            if seq:
                self.lines.append(
                    f"static const uint8_t {self.prefix}_{tag}{n}[] = {{{', '.join(str(VALTYPE_BYTES[t]) for t in seq)}}};"
                )
                parts.append(f"{self.prefix}_{tag}{n}")
            else:
                parts.append("0")
        return f"{{{len(ft.params)}u, {len(ft.results)}u, {parts[0]}, {parts[1]}}}"

    def ftype_of(self, t: Type) -> str:
        return self.types(t) if isinstance(t, FuncType) else "{0, 0, 0, 0}"

    def names(self, exp: ExportFact) -> str:
        if exp.param_names is None:
            return "0"
        n = self.count = self.count + 1
        items = ", ".join(_str(p) for p in exp.param_names)
        self.lines.append(f"static const wasmext_str {self.prefix}_n{n}[] = {{{items}}};")
        return f"{self.prefix}_n{n}"


def generate_descriptor(model: ModuleModel) -> str:
    """The C source: `<last>_describe()` returns the descriptor of the module."""
    em = _Emitter(f"{model.last}_desc")
    m = model.module
    memories = [_limits(x) for x in m.all_memories]
    tables = [f"{{{VALTYPE_BYTES[x.elem]}, {_limits(x.limits)}}}" for x in m.all_tables]
    globs = [f"{{{VALTYPE_BYTES[x.type]}, {int(x.mutable)}}}" for x in m.all_globals]
    tags = [em.types(x) for x in m.all_tags]
    imports = [_import(em, i) for i in model.imports]
    exports = [_export(em, e) for e in model.exports]

    p = em.prefix
    body = [
        "/* Generated by wasmext: the descriptor of the module (see wasmext_descriptor.h). Read-only data. */",
        '#include "wasmext_descriptor.h"',
        "",
        *em.lines,
        "",
    ]
    for name, ctype, items in (
        ("imports", "wasmext_import_desc", imports),
        ("exports", "wasmext_export_desc", exports),
        ("memories", "wasmext_limits", memories),
        ("tables", "wasmext_table_desc", tables),
        ("globals", "wasmext_global_desc", globs),
        ("tags", "wasmext_functype", tags),
    ):
        if items:
            body.append(f"static const {ctype} {p}_{name}[] = {{")
            body.extend(f"  {x}," for x in items)
            body.append("};")
        else:
            body.append(f"#define {p}_{name} 0")
    body += [
        "",
        f"static const wasmext_descriptor {p} = {{",
        "  WASMEXT_DESCRIPTOR_VERSION, sizeof(wasmext_descriptor),",
        f"  {_str(model.name)},",
        f"  {model.flags}u,",
        f"  {len(imports)}u, {p}_imports,",
        f"  {len(exports)}u, {p}_exports,",
        f"  {len(memories)}u, {p}_memories,",
        f"  {len(tables)}u, {p}_tables,",
        f"  {len(globs)}u, {p}_globals,",
        f"  {len(tags)}u, {p}_tags,",
        f"  {-1 if m.start is None else m.start}",
        "};",
        "",
        f"const wasmext_descriptor *{model.last}_describe(void) {{ return &{p}; }}",
        "",
    ]
    return "\n".join(body)


def _import(em: _Emitter, imp: ImportFact) -> str:
    return f"{{{_str(imp.module)}, {_str(imp.name)}, {KIND_CODES[imp.kind]}, {int(imp.core)}, {imp.index}u, {em.ftype_of(imp.type)}}}"


def _export(em: _Emitter, exp: ExportFact) -> str:
    return f"{{{_str(exp.name)}, {KIND_CODES[exp.kind]}, {exp.index}u, {em.ftype_of(exp.type)}, {em.names(exp)}}}"
